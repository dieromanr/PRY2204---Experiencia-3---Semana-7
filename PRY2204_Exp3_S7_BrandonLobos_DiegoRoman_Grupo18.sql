-- INFORME 1: Simulacion de Renta Promedio
SELECT nombre_empresa                              AS "Nombre Empresa",
       calle || ' ' || numeracion                  AS "Direccion",
       renta_promedio                              AS "Renta Promedio",
       ROUND(renta_promedio * (1 + pct_aumento))   AS "Simulacion de Renta"
FROM   compania
ORDER BY renta_promedio DESC, nombre_empresa ASC;

-- INFORME 2: Nueva simulacion de renta promedio (+15% sobre el porcentaje actual)
SELECT id_empresa                                       AS "Codigo",
       nombre_empresa                                   AS "Empresa",
       renta_promedio                                   AS "Prom Renta Actual",
       ROUND(pct_aumento + 0.15, 3)                     AS "Pct Aumentado en 15%",
       ROUND(renta_promedio * (pct_aumento + 0.15))     AS "Renta Aumentada"
FROM   compania
ORDER BY renta_promedio ASC, id_empresa DESC;
